# i386-compat.sh — the single place that knows how each image architecture
# gets a working 32-bit x86 userland for HLDS (hlds_linux, engine_i486.so,
# SteamCMD, amxxpc). Used by the Containerfile builder and runtime stages.
#
#   i386-compat.sh install [--runner] [extra-pkg...]
#       apt-get update + install the extra packages plus the i386 runtime
#       libraries for this architecture. On architectures that can't execute
#       i386 natively (arm64, …) it also installs a static qemu-i386 and the
#       hlds_linux launcher described below. --runner adds
#       /usr/local/bin/run-i386 for build-time tools (SteamCMD via its
#       $DEBUGGER hook, amxxpc): a plain exec on x86; elsewhere qemu-i386 with
#       the shim preloaded and a fake x86 /proc/cpuinfo.
#   i386-compat.sh packages
#       Print the i386 library package names for this architecture.
#
# Architectures:
#   amd64  biarch lib32* packages; i386 runs natively. Same packages as the
#          original Containerfile.
#   i386   native libraries (a linux/386 build stage).
#   other  Debian multiarch :i386 libraries, plus qemu-i386 user-mode
#          emulation. qemu-i386 is copied out of the qemu-user package (which
#          bundles every target, ~460 MB) and the package is purged, so the
#          image only carries the ~14 MB static i386 emulator. Also builds
#          i386-qemu-shim.so (see i386-qemu-shim.c; the cross compiler is
#          purged again).
#
# All architectures also get ca-certificates: without a CA bundle,
# steamclient.so logs "unable to load trusted SSL root certificates" and the
# server stays "disconnected from Steam3".
#
# Emulated launcher (non-x86 only), passed to hlds_run as `-binary` by
# entrypoint.sh:
#   /usr/local/libexec/cs-server/hlds_linux       sh wrapper (preloads the shim)
#   /usr/local/libexec/cs-server/emu/hlds_linux   symlink -> qemu-i386
# Running qemu through a symlink named hlds_linux keeps the process `comm`
# as "hlds_linux", so the existing HEALTHCHECK keeps working.
set -euo pipefail

EMU_DIR=/usr/local/libexec/cs-server
QEMU=/usr/local/bin/qemu-i386
SHIM=/usr/local/lib/i386-qemu-shim.so
FAKE_CPUINFO=/usr/local/share/cs-server/i386-cpuinfo
SCRIPT_DIR=$(cd "${BASH_SOURCE[0]%/*}" && pwd)
ARCH=$(dpkg --print-architecture)

case "${ARCH}" in
    amd64)
        PACKAGES=(lib32gcc-s1 lib32stdc++6 lib32z1 libc6-i386)
        EMULATE=0
        ;;
    i386)
        PACKAGES=(libgcc-s1 libstdc++6 zlib1g libc6)
        EMULATE=0
        ;;
    *)
        PACKAGES=(libgcc-s1:i386 libstdc++6:i386 zlib1g:i386 libc6:i386)
        EMULATE=1
        ;;
esac
PACKAGES+=(ca-certificates)

install_runner() {
    local exec_line='exec "$@"'
    if [[ "${EMULATE}" == "1" ]]; then
        # SteamCMD refuses to start without x86 CPU flags in /proc/cpuinfo.
        mkdir -p "${FAKE_CPUINFO%/*}"
        printf '%s\n' \
            'processor	: 0' \
            'vendor_id	: GenuineIntel' \
            'cpu family	: 6' \
            'model		: 85' \
            'model name	: Intel(R) Xeon(R) CPU (qemu-i386)' \
            'cpu MHz		: 3000.000' \
            'cache size	: 16384 KB' \
            'flags		: fpu vme de pse tsc msr pae mce cx8 apic sep mtrr pge mca cmov pat pse36 clflush mmx fxsr sse sse2 ht syscall nx lm constant_tsc pni ssse3 cx16 sse4_1 sse4_2 popcnt' \
            'bogomips	: 6000.00' \
            '' > "${FAKE_CPUINFO}"
        exec_line="exec ${QEMU} -E LD_PRELOAD=${SHIM} -E I386_FAKE_CPUINFO=${FAKE_CPUINFO} \"\$@\""
    fi
    printf '%s\n' \
        '#!/bin/sh' \
        '# Generated by i386-compat.sh: run an i386 binary on this architecture.' \
        "${exec_line}" \
        > /usr/local/bin/run-i386
    chmod 0755 /usr/local/bin/run-i386
}

install_emulator() {
    local build_deps=(qemu-user gcc-i686-linux-gnu libc6-dev-i386-cross)
    apt-get install -y --no-install-recommends "${build_deps[@]}"
    install -m 0755 /usr/bin/qemu-i386 "${QEMU}"
    i686-linux-gnu-gcc -O2 -shared -fPIC -Wall -Wextra -Werror \
        -o "${SHIM}" "${SCRIPT_DIR}/i386-qemu-shim.c" -ldl
    apt-get purge -y --auto-remove "${build_deps[@]}"
    mkdir -p "${EMU_DIR}/emu"
    ln -sf "${QEMU}" "${EMU_DIR}/emu/hlds_linux"
    printf '%s\n' \
        '#!/bin/sh' \
        '# Generated by i386-compat.sh: run the i386 HLDS binary under qemu-i386.' \
        "exec ${EMU_DIR}/emu/hlds_linux -E LD_PRELOAD=${SHIM} /hlds/hlds_linux \"\$@\"" \
        > "${EMU_DIR}/hlds_linux"
    chmod 0755 "${EMU_DIR}/hlds_linux"
    "${QEMU}" --version
}

do_install() {
    local runner=0
    if [[ "${1:-}" == "--runner" ]]; then
        runner=1
        shift
    fi
    if [[ "${ARCH}" != "i386" ]]; then
        dpkg --add-architecture i386
    fi
    apt-get update
    apt-get install -y --no-install-recommends "$@" "${PACKAGES[@]}"
    if [[ "${EMULATE}" == "1" ]]; then
        install_emulator
    fi
    if [[ "${runner}" == "1" ]]; then
        install_runner
    fi
}

cmd="${1:-}"
if [[ "$#" -gt 0 ]]; then
    shift
fi
case "${cmd}" in
    install) do_install "$@" ;;
    packages) echo "${PACKAGES[*]}" ;;
    *)
        echo "usage: $0 install [--runner] [extra-pkg...] | packages" >&2
        exit 2
        ;;
esac
